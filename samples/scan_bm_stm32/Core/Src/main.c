/**
 * @brief STM32U073RCTX bare-metal Wi-Fi scan sample using nRF70 BM library.
 *
 * This file is structured in STM32CubeIDE style: CubeMX generates peripheral
 * init code (MX_*_Init functions), and user code is placed in the designated
 * "USER CODE" regions.
 *
 * HOW IT WORKS
 * ------------
 * 1. CubeMX initialises clocks, SPI1, GPIO, UART, and the EXTI for HOST_IRQ.
 * 2. DWT cycle counter is enabled for microsecond-resolution busy-wait.
 * 3. nrf70_bm_sys_init() loads firmware, brings up the nRF70 RPU, and
 *    configures the scan-only mode.
 * 4. nrf70_bm_sys_scan_start() triggers a Wi-Fi scan.
 * 5. The superloop calls nrf70_process_timers() and nrf70_process_work() to
 *    service the driver cooperatively (no RTOS needed).
 * 6. Scan results arrive in scan_result_cb() and are printed via UART.
 *
 * IMPORTANT: In HAL_GPIO_EXTI_Callback(), call nrf70_host_irq_handler() to
 *            dispatch the HOST_IRQ to the driver.
 */

