#include "work.h"                  /* nrf70_process_work() */
#include "timer.h"                 /* nrf70_process_timers() */
#include "rpu_hw_if.h"             /* nrf70_host_irq_handler() */
#include <stdio.h>
#include <string.h>
/* USER CODE END Includes */

/* --------------------------------------------------------------------------
 * CubeMX-generated peripheral handles.
 * CubeMX will also declare them in main.h; keep in sync.
 * --------------------------------------------------------------------------*/
SPI_HandleTypeDef  hspi1;
UART_HandleTypeDef huart2;

/* USER CODE BEGIN PV */
static volatile bool g_scan_done = false;
/* USER CODE END PV */

/* --------------------------------------------------------------------------
 * Forward declarations of CubeMX-generated init functions
 * --------------------------------------------------------------------------*/
static void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_SPI1_Init(void);
static void MX_USART2_UART_Init(void);

/* --------------------------------------------------------------------------
 * Retarget printf to UART2 (newlib _write syscall)
 * --------------------------------------------------------------------------*/
/* USER CODE BEGIN 0 */
int _write(int file, char *ptr, int len)
{
    (void)file;
    HAL_UART_Transmit(&huart2, (uint8_t *)ptr, (uint16_t)len, HAL_MAX_DELAY);
    return len;
}
/* USER CODE END 0 */

/* --------------------------------------------------------------------------
 * Scan result callback — signature matches nrf70_bm_sys_scan_result_cb_t
 * --------------------------------------------------------------------------*/
/* USER CODE BEGIN 1 */
static void scan_result_cb(struct nrf70_bm_sys_scan_result *entry)
{
    if (entry == NULL) {
        /* NULL signals end-of-scan */
        printf("\r\n[scan] Scan complete.\r\n");
        g_scan_done = true;
        return;
    }

    /* entry->ssid is a uint8_t[NR70_SCAN_SSID_MAX_LEN], entry->ssid_len gives length */
    printf("[scan] SSID: %-32.*s  BSSID: %02X:%02X:%02X:%02X:%02X:%02X"
           "  RSSI: %d dBm  Ch: %u\r\n",
           entry->ssid_len, (const char *)entry->ssid,
           entry->bssid[0], entry->bssid[1], entry->bssid[2],
           entry->bssid[3], entry->bssid[4], entry->bssid[5],
           (int)entry->rssi,
           (unsigned)entry->channel);
}
/* USER CODE END 1 */

/* ==========================================================================
 * main()
 * ========================================================================== */
int main(void)
{
    /* USER CODE BEGIN Init */
    /* USER CODE END Init */

    /* MCU configuration — generated by CubeMX */
    HAL_Init();
    SystemClock_Config();

    /* USER CODE BEGIN SysInit */
    /* Enable DWT cycle counter for microsecond busy-wait in shim.c */
#if defined(DWT) && defined(CoreDebug)
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0;
    DWT->CTRL  |= DWT_CTRL_CYCCNTENA_Msk;
#endif
    /* USER CODE END SysInit */

    /* Peripheral init — generated by CubeMX */
    MX_GPIO_Init();
    MX_SPI1_Init();
    MX_USART2_UART_Init();

    /* USER CODE BEGIN 2 */
    printf("\r\n========================================\r\n");
    printf("  nRF70 BM Wi-Fi Scan - STM32U073RCTX\r\n");
    printf("========================================\r\n\r\n");

    /* MAC address: all-zeros → library reads from OTP */
    uint8_t mac_addr[6] = {0};

    /* Regulatory info: country code (char[2], NOT NUL-terminated) */
    struct nrf70_bm_regulatory_info reg_info = {
        .country_code = {'U', 'S'},
        .force        = false,
    };

    /* Initialise the nRF70 BM library */
    int ret = nrf70_bm_sys_init(mac_addr, &reg_info);
    if (ret != 0) {
        printf("[main] nrf70_bm_sys_init failed: %d\r\n", ret);
        while (1) { }
    }

    printf("[main] nRF70 initialised. Starting Wi-Fi scan...\r\n\r\n");

    /* Configure scan parameters */
    struct nrf70_bm_sys_scan_params scan_params = {
        .scan_type         = NRF70_SCAN_TYPE_ACTIVE,
        .dwell_time_active  = 50,   /* ms per channel */
        .dwell_time_passive = 130,  /* ms for passive channels */
        .max_bss_cnt        = 0,    /* 0 = no limit */
    };

    ret = nrf70_bm_sys_scan_start(&scan_params, scan_result_cb);
    if (ret != 0) {
        printf("[main] nrf70_bm_sys_scan_start failed: %d\r\n", ret);
    }
    /* USER CODE END 2 */

    /* =======================================================================
     * Superloop
     * ======================================================================= */
    while (1) {
        /* USER CODE BEGIN WHILE */

        /* Service expired software timers */
        nrf70_process_timers();

        /* Execute deferred work items (bottom-half processing) */
        nrf70_process_work();

        /* Restart scan every 10 seconds after scan completes */
        if (g_scan_done) {
            g_scan_done = false;
            HAL_Delay(10000);
            printf("\r\n[main] Starting next scan...\r\n\r\n");
            nrf70_bm_sys_scan_start(&scan_params, scan_result_cb);
        }

        /* USER CODE END WHILE */
    }
}

/* ==========================================================================
 * EXTI callback — called from HAL_GPIO_EXTI_IRQHandler()
 * MUST dispatch to nrf70_host_irq_handler() for HOST_IRQ pin.
 * ========================================================================== */
/* USER CODE BEGIN 4 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    if (GPIO_Pin == NRF70_IRQ_PIN) {
        /* Dispatch HOST_IRQ to the nRF70 driver */
        nrf70_host_irq_handler();

        /* Run any work items queued by the IRQ handler immediately */
        nrf70_process_work();
    }
}
/* USER CODE END 4 */

